/// Coordinates are doubles in RESP3, and what's missing the one null.
#[tokio::test]
async fn geo_in_resp3() {
    let (addr, _ctx) = start(Mode::PerThread).await;
    let mut c = Client::connect(addr).await;
    c.call(&["HELLO", "3"]).await;
    for (args, expected) in [
        (
            &["GEOADD", "s", "13.361389", "38.115556", "Palermo"][..],
            ":1\r\n",
        ),
        (
            &["GEOPOS", "s", "Palermo", "Nowhere"],
            "*2\r\n*2\r\n,13.36138933897018433\r\n,38.11555639549629859\r\n_\r\n",
        ),
        (&["GEOHASH", "s", "Nowhere"], "*1\r\n_\r\n"),
        (&["GEODIST", "s", "Palermo", "Nowhere"], "_\r\n"),
        (&["GEODIST", "s", "Palermo", "Palermo"], "$6\r\n0.0000\r\n"),
        (
            &[
                "GEOSEARCH",
                "s",
                "FROMLONLAT",
                "13.361389",
                "38.115556",
                "BYRADIUS",
                "1",
                "km",
                "WITHCOORD",
            ],
            "*1\r\n*2\r\n$7\r\nPalermo\r\n*2\r\n,13.36138933897018433\r\n,38.11555639549629859\r\n",
        ),
    ] {
        assert_eq!(c.call(args).await, expected, "{args:?}");
    }
}

/// A command's new value takes the place of what the key held, its expiry too.
#[tokio::test]
async fn what_stores_a_result_forgets_the_old_expiry() {
    let mut c = connect().await;
    for (args, expected) in [
        (&[&b"ZADD"[..], b"z", b"1", b"a"][..], &b":1\r\n"[..]),
        (&[b"SADD", b"s", b"a"], b":1\r\n"),
        (&[b"GEOADD", b"g", b"1", b"2", b"a"], b":1\r\n"),
    ] {
        check(&mut c, &req(args), expected).await;
    }
    let stores: [&[&[u8]]; 9] = [
        &[b"ZUNIONSTORE", b"d", b"1", b"z"],
        &[b"ZINTERSTORE", b"d", b"1", b"z"],
        &[b"ZDIFFSTORE", b"d", b"1", b"z"],
        &[b"ZRANGESTORE", b"d", b"z", b"0", b"-1"],
        &[b"SUNIONSTORE", b"d", b"s"],
        &[b"SINTERSTORE", b"d", b"s"],
        &[b"SDIFFSTORE", b"d", b"s"],
        &[b"GEORADIUS", b"g", b"1", b"2", b"1", b"km", b"STORE", b"d"],
        &[
            b"GEOSEARCHSTORE",
            b"d",
            b"g",
            b"FROMLONLAT",
            b"1",
            b"2",
            b"BYRADIUS",
            b"1",
            b"km",
        ],
    ];
    for store in stores {
        check(
            &mut c,
            &req(&[b"SET", b"d", b"x", b"EX", b"100"]),
            b"+OK\r\n",
        )
        .await;
        check(&mut c, &req(store), b":1\r\n").await;
        check(&mut c, &req(&[b"TTL", b"d"]), b":-1\r\n").await;
    }
}

/// One added to a little at a time, as it moves to a place of its own and then
/// turns dense, goes on counting, and keeps its expiry.
#[tokio::test]
async fn a_hyperloglog_keeps_on_counting() {
    let (addr, _ctx) = start(Mode::PerThread).await;
    let mut c = Client::connect(addr).await;
    assert_eq!(c.call(&["PFADD", "t", "element:0"]).await, ":1\r\n");
    assert_eq!(c.call(&["EXPIRE", "t", "1000"]).await, ":1\r\n");
    for i in 1..20_000 {
        let element = format!("element:{i}");
        assert!(c.call(&["PFADD", "t", &element]).await.starts_with(':'));
        if i % 2000 == 0 {
            let reply = c.call(&["PFCOUNT", "t"]).await;
            let count: i64 = reply[1..].trim().parse().unwrap();
            assert!((count - i).abs() <= i / 20 + 2, "{i}: {count}");
        }
    }
    assert_eq!(c.call(&["PFDEBUG", "ENCODING", "t"]).await, "+dense\r\n");
    assert!(c.call(&["TTL", "t"]).await != ":-1\r\n");
    assert_eq!(c.call(&["PFADD", "t", "element:7"]).await, ":0\r\n");
}

/// Each register, and the hash that puts an element in one.
#[tokio::test]
async fn pfdebug_shows_the_registers() {
    let (addr, _ctx) = start(Mode::PerThread).await;
    let mut c = Client::connect(addr).await;
    assert_eq!(c.call(&["PFADD", "h", "a", "b", "c"]).await, ":1\r\n");
    let registers = c.call(&["PFDEBUG", "GETREG", "h"]).await;
    let mut lines = registers.lines();
    assert_eq!(lines.next(), Some("*16384"));
    let set: Vec<&str> = lines.filter(|line| *line != ":0").collect();
    assert_eq!(set.len(), 3, "{set:?}");
    assert_eq!(c.call(&["PFDEBUG", "ENCODING", "h"]).await, "+dense\r\n");
    assert_eq!(c.call(&["PFCOUNT", "h"]).await, ":3\r\n");
}
