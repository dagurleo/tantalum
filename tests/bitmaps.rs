#[tokio::test]
async fn resp3_replies() {
    let mut client = connect_buffered().await;
    let mut ask = async |args: &[&[u8]]| {
        client.stream.get_mut().write_all(&req(args)).await.unwrap();
        client.raw_reply().await
    };
    ask(&[b"HELLO", b"3"]).await;
    assert_eq!(
        ask(&[
            b"BITFIELD",
            b"f",
            b"OVERFLOW",
            b"FAIL",
            b"INCRBY",
            b"u2",
            b"0",
            b"9"
        ])
        .await,
        b"*1\r\n_\r\n"
    );
    assert_eq!(
        ask(&[b"BITFIELD", b"f", b"GET", b"u2", b"0"]).await,
        b"*1\r\n:0\r\n"
    );
}

/// A `SETBIT` in a big bitmap must not copy it: 100,000 of them in a 12.5 MB one
/// would take minutes if each did.
#[tokio::test]
async fn setbit_in_a_big_bitmap_does_not_copy_it() {
    let mut client = connect_buffered().await;
    let mut ask = async |args: &[&[u8]]| {
        client.stream.get_mut().write_all(&req(args)).await.unwrap();
        client.raw_reply().await
    };
    ask(&[b"SETBIT", b"map", b"100000000", b"1"]).await;
    let started = Instant::now();
    let mut expected = 1;
    for i in 0..100_000u64 {
        let offset = (i * 997).to_string();
        assert_eq!(
            ask(&[b"SETBIT", b"map", offset.as_bytes(), b"1"]).await,
            b":0\r\n"
        );
        expected += 1;
    }
    assert!(
        started.elapsed() < Duration::from_secs(60),
        "{:?}",
        started.elapsed()
    );
    assert_eq!(
        ask(&[b"BITCOUNT", b"map"]).await,
        format!(":{expected}\r\n").as_bytes()
    );
    assert_eq!(ask(&[b"GETBIT", b"map", b"997"]).await, b":1\r\n");
    assert_eq!(ask(&[b"GETBIT", b"map", b"998"]).await, b":0\r\n");
    assert_eq!(ask(&[b"STRLEN", b"map"]).await, b":12500001\r\n");
}

/// Small appends to a big string add up, past each point where it has to move.
#[tokio::test]
async fn appends_to_a_big_string_add_up() {
    let mut client = connect_buffered().await;
    let mut ask = async |args: &[&[u8]]| {
        client.stream.get_mut().write_all(&req(args)).await.unwrap();
        client.raw_reply().await
    };
    let mut model = Vec::new();
    for i in 0..30_000u32 {
        let piece = format!("{i:08}");
        model.extend_from_slice(piece.as_bytes());
        let len = format!(":{}\r\n", model.len());
        assert_eq!(
            ask(&[b"APPEND", b"log", piece.as_bytes()]).await,
            len.as_bytes()
        );
    }
    let reply = ask(&[b"GET", b"log"]).await;
    let header = format!("${}\r\n", model.len());
    assert_eq!(&reply[..header.len()], header.as_bytes());
    assert!(
        reply[header.len()..reply.len() - 2] == model[..],
        "the bytes differ"
    );
}
